#!/usr/bin/env python3
"""Writes include/nuzlocke_data.h, the tables the Nuzlocke rules (NUZLOCKE, docs/nuzlocke.md) read:

    gen_nuzlocke_data.py [OUTPUT]

- the place of every zone (each zone's `place` in res/field/zones), since a route, cave or town counts once however many
  zones it has;
- one saved event flag for each place, which says that its wild encounter has been used, and one for a failed
  challenge. They are saved flags that nothing in scripts, events or code names, in the three longest runs of them
  below the trainers' flags: the game's own flag lists (generated/flags.txt) leave them unused;
- the legendary and pseudo-legendary species, which can't be caught.

The output is committed: run this again after the zones or the flag lists change.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.data.gen_constants import load as load_list  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
TRAINER_FLAGS_START = 0x5F0
# The first flags are the new game's: the intro's scripts may reset them
EARLY_FLAGS_END = 0x100

LEGENDARY = """ARTICUNO ZAPDOS MOLTRES MEWTWO MEW RAIKOU ENTEI SUICUNE LUGIA HO_OH CELEBI REGIROCK REGICE REGISTEEL LATIAS
LATIOS KYOGRE GROUDON RAYQUAZA JIRACHI DEOXYS UXIE MESPRIT AZELF DIALGA PALKIA HEATRAN REGIGIGAS GIRATINA CRESSELIA
PHIONE MANAPHY DARKRAI SHAYMIN ARCEUS VICTINI COBALION TERRAKION VIRIZION TORNADUS THUNDURUS RESHIRAM ZEKROM LANDORUS
KYUREM KELDEO MELOETTA GENESECT""".split()
PSEUDO_LEGENDARY = """DRATINI DRAGONAIR DRAGONITE LARVITAR PUPITAR TYRANITAR BAGON SHELGON SALAMENCE BELDUM METANG
METAGROSS GIBLE GABITE GARCHOMP DEINO ZWEILOUS HYDREIGON""".split()


def unused_flag_runs() -> list[list[int]]:
    """The runs of saved flags below the trainers' that no file names, longest first."""
    flags = load_list("flags")
    found = subprocess.run(["grep", "-rhoE", r"EVENT_FLAG_[A-Za-z0-9_]+", "src", "include", "res", "lib", "tools"],
                           cwd=ROOT, capture_output=True, text=True).stdout.split()
    named = set(found)
    free = sorted(v for n, v in flags.items() if EARLY_FLAGS_END < v < TRAINER_FLAGS_START and n not in named)
    runs: list[list[int]] = []
    for value in free:
        if runs and value == runs[-1][-1] + 1:
            runs[-1].append(value)
        else:
            runs.append([value])
    runs.sort(key=len, reverse=True)
    return runs[:3]


def main():
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "include" / "nuzlocke_data.h"
    zones = load_list("zones")
    places = load_list("places")
    species = load_list("species")

    zone_places = [0] * (max(zones.values()) + 1)
    for name, value in zones.items():
        data = json.loads((ROOT / "res/field/zones" / f"{name.removeprefix('ZONE_').lower()}.json").read_text())
        zone_places[value] = places[data["place"]]

    flags = [flag for run in unused_flag_runs() for flag in run]
    place_count = max(places.values()) + 1
    if len(flags) < place_count + 1:
        sys.exit(f"only {len(flags)} unused flags for {place_count} places")
    failed_flag, place_flags = flags[0], flags[1:place_count + 1]

    banned = []
    for name in LEGENDARY + PSEUDO_LEGENDARY:
        constant = f"SPECIES_{name}"
        if constant not in species:
            sys.exit(f"unknown species {constant}")
        banned.append(species[constant])
    banned.sort()

    def rows(values, per_line, fmt):
        return ",\n".join("    " + ", ".join(fmt.format(v) for v in values[i:i + per_line])
                          for i in range(0, len(values), per_line))

    text = f"""// Generated by tools/randomizer/gen_nuzlocke_data.py: the tables of the Nuzlocke rules, see docs/nuzlocke.md
#ifndef POKEBW2_NUZLOCKE_DATA_H
#define POKEBW2_NUZLOCKE_DATA_H

#define NUZLOCKE_ZONE_COUNT {len(zone_places)}
#define NUZLOCKE_PLACE_COUNT {place_count}
#define NUZLOCKE_BANNED_COUNT {len(banned)}

// The saved event flag that says the challenge is lost
#define NUZLOCKE_FAILED_FLAG {failed_flag:#06x}

// The saved event flag of each place, which says its wild encounter has been used
static const u16 sNuzlockePlaceFlags[NUZLOCKE_PLACE_COUNT] = {{
{rows(place_flags, 8, "{:#06x}")},
}};

// The place of each zone
static const u8 sNuzlockeZonePlaces[NUZLOCKE_ZONE_COUNT] = {{
{rows(zone_places, 16, "{}")},
}};

// The legendary and pseudo-legendary species ({len(banned)}), which can't be caught
static const u16 sNuzlockeBannedSpecies[NUZLOCKE_BANNED_COUNT] = {{
{rows(banned, 12, "{}")},
}};

#endif // POKEBW2_NUZLOCKE_DATA_H
"""
    output.write_text(text)
    print(f"Wrote {output}: {len(zone_places)} zones, {place_count} places, {len(banned)} banned species, "
          f"flags {failed_flag:#06x} and {place_flags[0]:#06x}-{place_flags[-1]:#06x}")


if __name__ == "__main__":
    main()
